-- Schema of the anonymous assistant log. Run it ONCE, as the database owner, on an empty database.
--
--   psql "$OWNER_DATABASE_URL" -v ON_ERROR_STOP=1 -f backend/sql/schema.sql
--
-- On Neon you can also paste the whole file into the SQL editor. It is one transaction: if any
-- statement fails, nothing is created, so you can fix it and run it again.
--
-- Afterwards run backend/sql/roles.sql and backend/sql/retention_role.sql, then
-- `alembic stamp head` from backend/ so Alembic knows the database is already at the latest
-- revision. This file always describes the latest schema, the same one the migrations in
-- alembic/versions/ reach when they are applied in order.
--
-- No IP, user agent, email or other identifier is stored (rule DATA-03).

BEGIN;

CREATE TABLE chat_messages (
  -- The id is generated by the app, before the answer is sent, so the browser can rate it.
  id                uuid        NOT NULL,
  created_at        timestamptz NOT NULL DEFAULT now(),
  locale            text        NOT NULL,
  question          text        NOT NULL,
  answer            text,
  status            text        NOT NULL,
  -- 'none' means no model was called (quick answers, refusals by the guard, rate limits).
  provider          text        NOT NULL,
  latency_ms        integer     NOT NULL,
  prompt_tokens     integer,
  completion_tokens integer,
  cached_tokens     integer,
  knowledge_version text        NOT NULL,
  -- Explicit constraint names match the SQLAlchemy naming convention, so later migrations
  -- can drop them by name.
  CONSTRAINT pk_chat_messages PRIMARY KEY (id),
  CONSTRAINT ck_chat_messages_locale_valid CHECK (locale IN ('es', 'en')),
  CONSTRAINT ck_chat_messages_question_length CHECK (length(question) BETWEEN 1 AND 1000),
  CONSTRAINT ck_chat_messages_answer_length
    CHECK (answer IS NULL OR length(answer) BETWEEN 1 AND 2000),
  CONSTRAINT ck_chat_messages_status_valid CHECK (status IN (
    'answered', 'answered_quick', 'answered_cached', 'refused_off_topic', 'refused_injection',
    'rate_limited', 'provider_error', 'invalid_output')),
  CONSTRAINT ck_chat_messages_provider_valid CHECK (provider IN ('groq', 'gemini', 'none')),
  -- An answered row always has its answer and the provider that produced it.
  CONSTRAINT ck_chat_messages_answered_has_answer
    CHECK (status NOT IN ('answered', 'answered_quick', 'answered_cached') OR answer IS NOT NULL),
  CONSTRAINT ck_chat_messages_answered_by_llm
    CHECK (status <> 'answered' OR provider IN ('groq', 'gemini')),
  CONSTRAINT ck_chat_messages_quick_without_llm
    CHECK (status <> 'answered_quick' OR provider = 'none'),
  CONSTRAINT ck_chat_messages_cached_without_llm
    CHECK (status <> 'answered_cached' OR provider = 'none'),
  -- Off-topic refusals and invalid output both come from a model call.
  CONSTRAINT ck_chat_messages_model_result_has_provider
    CHECK (status NOT IN ('refused_off_topic', 'invalid_output') OR provider <> 'none'),
  -- Tokens only exist when a model was called.
  CONSTRAINT ck_chat_messages_tokens_need_provider
    CHECK (provider <> 'none'
      OR (prompt_tokens IS NULL AND completion_tokens IS NULL AND cached_tokens IS NULL)),
  CONSTRAINT ck_chat_messages_latency_nonnegative CHECK (latency_ms >= 0),
  -- A CHECK passes when a value is NULL, so the nullable counters need no coalesce.
  CONSTRAINT ck_chat_messages_tokens_nonnegative
    CHECK (prompt_tokens >= 0 AND completion_tokens >= 0 AND cached_tokens >= 0),
  CONSTRAINT ck_chat_messages_cached_within_prompt
    CHECK (cached_tokens IS NULL OR prompt_tokens IS NULL OR cached_tokens <= prompt_tokens),
  CONSTRAINT ck_chat_messages_knowledge_version_length
    CHECK (length(knowledge_version) BETWEEN 1 AND 64)
);

-- The retention job deletes by age and reviews read the newest rows first.
CREATE INDEX ix_chat_messages_created_at ON chat_messages (created_at);

-- One rating per message. A repeated rating is ignored (INSERT ... ON CONFLICT DO NOTHING).
CREATE TABLE feedback (
  id         uuid        NOT NULL,
  message_id uuid        NOT NULL,
  helpful    boolean     NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pk_feedback PRIMARY KEY (id),
  CONSTRAINT fk_feedback_message_id_chat_messages
    FOREIGN KEY (message_id) REFERENCES chat_messages (id) ON DELETE CASCADE,
  -- This unique index also serves the foreign key lookups.
  CONSTRAINT uq_feedback_message_id UNIQUE (message_id)
);

COMMIT;
