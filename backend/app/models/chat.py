"""ORM models for the anonymous assistant log and the answer ratings.

These classes mirror backend/sql/schema.sql and the first Alembic migration. The rules live in
the database as constraints, so no code path can store an invalid row. No IP, user agent or
other identifier is stored (DATA-03).
"""

import uuid
from datetime import datetime
from enum import StrEnum

from sqlalchemy import Boolean, CheckConstraint, DateTime, ForeignKey, Integer, Text, Uuid, func
from sqlalchemy.orm import Mapped, mapped_column

from app.core.locale import Locale
from app.db.base import Base

QUESTION_MAX_LENGTH = 1000
ANSWER_MAX_LENGTH = 2000
KNOWLEDGE_VERSION_MAX_LENGTH = 64


class ChatStatus(StrEnum):
    """What happened to a question. Stored as text; the database restricts it to these."""

    ANSWERED = "answered"
    ANSWERED_QUICK = "answered_quick"
    REFUSED_OFF_TOPIC = "refused_off_topic"
    REFUSED_INJECTION = "refused_injection"
    RATE_LIMITED = "rate_limited"
    PROVIDER_ERROR = "provider_error"
    INVALID_OUTPUT = "invalid_output"


class LlmProvider(StrEnum):
    """Who produced the answer. NONE means no model was called."""

    GROQ = "groq"
    GEMINI = "gemini"
    NONE = "none"


def _in_list(column: str, values: type[StrEnum]) -> str:
    return f"{column} IN ({', '.join(repr(member.value) for member in values)})"


class ChatMessage(Base):
    __tablename__ = "chat_messages"
    # Constraint names are short because the naming convention adds "ck_chat_messages_".
    __table_args__ = (
        CheckConstraint(_in_list("locale", Locale), name="locale_valid"),
        CheckConstraint(f"length(question) BETWEEN 1 AND {QUESTION_MAX_LENGTH}", "question_length"),
        CheckConstraint(
            f"answer IS NULL OR length(answer) BETWEEN 1 AND {ANSWER_MAX_LENGTH}",
            "answer_length",
        ),
        CheckConstraint(_in_list("status", ChatStatus), name="status_valid"),
        CheckConstraint(_in_list("provider", LlmProvider), name="provider_valid"),
        # An answered row always has its answer and the provider that produced it.
        CheckConstraint(
            "status NOT IN ('answered', 'answered_quick') OR answer IS NOT NULL",
            name="answered_has_answer",
        ),
        CheckConstraint(
            "status <> 'answered' OR provider IN ('groq', 'gemini')", name="answered_by_llm"
        ),
        CheckConstraint(
            "status <> 'answered_quick' OR provider = 'none'", name="quick_without_llm"
        ),
        # Off-topic refusals and invalid output both come from a model call.
        CheckConstraint(
            "status NOT IN ('refused_off_topic', 'invalid_output') OR provider <> 'none'",
            name="model_result_has_provider",
        ),
        # Tokens only exist when a model was called.
        CheckConstraint(
            "provider <> 'none' OR (prompt_tokens IS NULL AND completion_tokens IS NULL "
            "AND cached_tokens IS NULL)",
            name="tokens_need_provider",
        ),
        CheckConstraint("latency_ms >= 0", name="latency_nonnegative"),
        # A CHECK passes when a value is NULL, so the nullable counters need no coalesce.
        CheckConstraint(
            "prompt_tokens >= 0 AND completion_tokens >= 0 AND cached_tokens >= 0",
            name="tokens_nonnegative",
        ),
        CheckConstraint(
            "cached_tokens IS NULL OR prompt_tokens IS NULL OR cached_tokens <= prompt_tokens",
            name="cached_within_prompt",
        ),
        CheckConstraint(
            f"length(knowledge_version) BETWEEN 1 AND {KNOWLEDGE_VERSION_MAX_LENGTH}",
            name="knowledge_version_length",
        ),
    )

    # Generated by the app before the answer is sent, so the browser can rate that message.
    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), index=True
    )
    locale: Mapped[str] = mapped_column(Text)
    question: Mapped[str] = mapped_column(Text)
    answer: Mapped[str | None] = mapped_column(Text)
    status: Mapped[str] = mapped_column(Text)
    provider: Mapped[str] = mapped_column(Text)
    latency_ms: Mapped[int] = mapped_column(Integer)
    prompt_tokens: Mapped[int | None] = mapped_column(Integer)
    completion_tokens: Mapped[int | None] = mapped_column(Integer)
    cached_tokens: Mapped[int | None] = mapped_column(Integer)
    knowledge_version: Mapped[str] = mapped_column(Text)


class Feedback(Base):
    """One rating per message. A repeated rating is ignored by INSERT ... ON CONFLICT."""

    __tablename__ = "feedback"

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True)
    # The unique constraint also serves as the index for the foreign key lookups.
    message_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("chat_messages.id", ondelete="CASCADE"), unique=True
    )
    helpful: Mapped[bool] = mapped_column(Boolean)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
